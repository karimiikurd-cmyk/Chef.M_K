    fun getAllCuts(): List<MeatCut> = cuts

    fun getCutById(id: String): MeatCut? = cuts.find { it.id == id }

    fun filterCuts(category: MeatCategory, query: String): List<MeatCut> {
        var list = if (category == MeatCategory.ALL) cuts else cuts.filter { it.category == category }
        if (query.isNotBlank()) {
            val q = query.trim().lowercase()
            list = list.filter { cut ->
                cut.persianName.lowercase().contains(q) ||
                cut.englishName.lowercase().contains(q) ||
                cut.animal.lowercase().contains(q) ||
                cut.anatomicalLocation.lowercase().contains(q) ||
                cut.suitableCookingMethods.lowercase().contains(q) ||
                cut.relatedRecipeKeywords.any { it.lowercase().contains(q) }
            }
        }
        return list
    }
